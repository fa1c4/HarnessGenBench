# 7. Intended APIs alone do not complete reachability.
# ---------------------------------------------------------------------------


def test_intended_apis_alone_do_not_complete_reachability() -> None:
    """Reachability requires dynamic execution evidence, not just the intended
    API list."""
    intended = ["foo", "bar", "baz"]
    # Empty executed_functions -> no reachability.
    reach = hgb_reachability.check_reachability(intended, {"executed_functions": []})
    assert reach["reached"] is False
    assert reach["reached_apis"] == []
    # Intended APIs passed as executed_functions IS evidence, but only if they
    # appear in the coverage trace.  An empty trace must not match.
    reach2 = hgb_reachability.check_reachability(intended, {"executed_functions": []})
    assert reach2["reached_count"] == 0


def test_reachability_requires_coverage_evidence_not_intended_only() -> None:
    """The evaluator uses covered_functions from the coverage report, not the
    intended API list, as the execution trace."""
    intended = ["foo", "bar"]
    # Simulate a coverage report with NO covered functions.
    cov_summary = {"covered_functions": []}
    covered_functions = cov_summary.get("covered_functions", [])
    reach = hgb_reachability.check_reachability(intended, {"executed_functions": covered_functions})
    assert reach["reached"] is False
    # With real coverage evidence, reachability succeeds.
    cov_summary2 = {"covered_functions": ["foo", "other"]}
    covered2 = cov_summary2.get("covered_functions", [])
    reach2 = hgb_reachability.check_reachability(intended, {"executed_functions": covered2})
    assert reach2["reached"] is True
    assert "foo" in reach2["reached_apis"]


