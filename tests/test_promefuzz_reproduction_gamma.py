def test_embedding_preflight_skips_for_mock_local_hash() -> None:
    """The preflight script must skip (not fail) for mock/local/hash, but
    the profile validation must forbid those types in reproduction-gamma."""
    import tempfile
    with tempfile.NamedTemporaryFile(mode="w", suffix=".log", delete=False) as f:
        log_file = f.name
    # Write and run the preflight script with mock type.
    import os
    env = os.environ.copy()
    env["PROME_FUZZ_EMBEDDING_LLM_TYPE"] = "mock"
    env["PROME_FUZZ_EMBEDDING_PREFLIGHT"] = "1"
    # Extract the preflight script from the entrypoint and run it.
    script = _extract_preflight_script()
    if script:
        proc = subprocess.run(
            [sys.executable, "-c", script], capture_output=True, text=True,
            env=env, timeout=30,
        )
        # mock/local/hash should be skipped (exit 0) but forbidden by the profile.
        assert proc.returncode == 0
        assert "skipped" in proc.stdout.lower() or "compat-smoke" in proc.stdout.lower()


def _extract_preflight_script() -> str:
    """Extract the embedding preflight Python script from the entrypoint."""
    entrypoint = _entrypoint()
    start_marker = "PY_PROMEFUZZ_EMBEDDING_PREFLIGHT"
    # The script is between the heredoc markers.
    start = entrypoint.find("<<'" + start_marker + "'")
    if start == -1:
        return ""
    start += len("<<'" + start_marker + "'")
    end = entrypoint.find(start_marker, start)
    if end == -1:
        return ""
    return entrypoint[start:end].strip()


