def test_split_package_metadata_loads_from_generator_half(tmp_path: Path) -> None:
    pkg = _make_monolithic_package(tmp_path)
    halves = hgb_target_package.split_package(
        pkg,
        native_harness={
            "selected_reference": "source_input/project/native.c",
            "container_destination": "/src/project/native.c",
            "language": "c",
        },
    )
    gen = Path(halves["generator_input"])
    evl = Path(halves["evaluator_only"])
    # Generator half has the sanitized manifest at both canonical names.
    assert (gen / "target_manifest.json").is_file()
    assert (gen / "target_manifest.generator.json").is_file()
    # Evaluator half has the evaluator manifest at both canonical names.
    assert (evl / "evaluator_manifest.json").is_file()
    assert (evl / "target_manifest.evaluator.json").is_file()
    # Load metadata from the generator half alone (no monolithic root needed).
    gen_manifest = hgb_target_package.load_generator_manifest(gen)
    assert gen_manifest["project"] == "project"
    assert gen_manifest["fuzz_target"] == "fuzz_target"
    # Generator manifest must not leak reference-harness fields.
    assert not hgb_target_package.generator_manifest_has_no_reference_fields(gen_manifest)
    # Evaluator manifest loads from the evaluator half.
    ev_manifest = hgb_target_package.load_evaluator_manifest(evl)
    assert ev_manifest["project"] == "project"
    assert ev_manifest["native_harness_destination"] == "/src/project/native.c"


