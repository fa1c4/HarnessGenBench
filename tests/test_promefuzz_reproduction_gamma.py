def test_exact_fuzzbench_capture_method_prefers_bear_replay(tmp_path: Path) -> None:
    """exact_fuzzbench tries bear_replay before cmake_export."""
    target_root, src = _make_fixture_target(tmp_path)
    work = tmp_path / "work"
    # Use a runner that records the method order.
    call_order: list[str] = []

    class _RecordingRunner:
        def __call__(self, command, timeout=None):
            call_order.append(command[0] if command else "")
            return build_context._real_runner(command, timeout)

    manifest = build_context.capture_build_context(
        target_root=target_root, work_dir=work, fuzz_target="fuzz_foo",
        language="c", profile="reproduction-gamma", allow_synthetic=False,
        capture_method="exact_fuzzbench", source_root=src,
        runner=_RecordingRunner(),
    )
    # exact_fuzzbench should have tried bear first (bear may not be installed,
    # so it falls back to cmake, but the method order is bear then cmake).
    assert manifest["synthetic"] is False
    # The capture method is recorded as the one that produced results.
    assert manifest["capture_method"] in {"bear_replay", "cmake_export"}


