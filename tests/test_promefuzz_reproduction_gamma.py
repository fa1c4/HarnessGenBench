def test_evaluator_argparse_accepts_promefuzz_entrypoint_command(tmp_path: Path) -> None:
    """The exact evaluator command constructed by entrypoint.sh must parse.

    This is the regression test for the gamma plan section 5 deterministic
    CLI error: the entrypoint previously passed ``--build-timeout`` but the
    evaluator only defined ``--build-timeout-seconds``.
    """
    entrypoint = _entrypoint()
    assert "--build-timeout-seconds" in entrypoint
    # The evaluator invocation must use --build-timeout-seconds, not --build-timeout.
    # (promefuzz_build_context.py legitimately uses --build-timeout for its own CLI.)
    assert '--build-timeout-seconds "${HGB_PROMEFUZZ_EVAL_BUILD_TIMEOUT:-1800}"' in entrypoint
    assert '--build-timeout "${HGB_PROMEFUZZ_EVAL_BUILD_TIMEOUT' not in entrypoint
    # Construct the exact argv the entrypoint builds.
    target_root = tmp_path / "target"
    evaluator_root = tmp_path / "evaluator"
    candidates = tmp_path / "candidates"
    work_dir = tmp_path / "eval"
    target_root.mkdir()
    evaluator_root.mkdir()
    candidates.mkdir()
    work_dir.mkdir()
    (target_root / "target_manifest.json").write_text(
        json.dumps({"project": "foo", "fuzz_target": "fuzz_foo"}), encoding="utf-8"
    )
    (candidates / "cand_001.c").write_text("// stub\n", encoding="utf-8")
    argv = [
        sys.executable, str(REPO_ROOT / "docker/common/hgb_harness_evaluator.py"),
        "--generator", "promefuzz",
        "--target-root", str(target_root),
        "--evaluator-root", str(evaluator_root),
        "--candidates", str(candidates),
        "--work-dir", str(work_dir),
        "--project", "foo",
        "--fuzz-target", "fuzz_foo",
        "--profile", "reproduction-gamma",
        "--campaign-seconds", "300",
        "--build-timeout-seconds", "1800",
        "--strict",
        "--intended-apis", "foo,bar",
    ]
    # The parser must accept all flags without argparse error.  We run with
    # --help so it exits 0 after parsing (no Docker needed).
    proc = subprocess.run(argv + ["--help"], capture_output=True, text=True, timeout=30)
    assert proc.returncode == 0, f"argparse rejected entrypoint command:\n{proc.stderr}"
    assert "--build-timeout-seconds" in proc.stdout


